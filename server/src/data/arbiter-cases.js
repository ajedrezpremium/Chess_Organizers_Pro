function norm(s) {
  return String(s || '').toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
}

function caseWords(c) {
  return norm(`${c.topic} ${c.title} ${c.a}`).split(/[^a-z0-9]+/).filter((w) => w.length > 4);
}

/**
 * Busca casos por patrones (10 pts) u overlap de palabras (1 pt).
 * Devuelve [{...case, _score}] ordenados. Umbral de respuesta: >= 10.
 */
export function searchArbiterCases(question, limit = 3) {
  const q = norm(question);
  const teamCtx = /(equipo|match|capitan|alineaci|liga|club)/.test(q);
  const scored = [];
  for (const c of ARBITER_CASES) {
    let score = 0;
    for (const p of c.patterns) {
      const np = norm(p);
      if (!np) continue;
      if (q.includes(np) || (np.length > 8 && np.includes(q))) score += 10;
    }
    if (score === 0) {
      const text = caseWords(c).join(' ');
      const words = q.split(/[^a-z0-9]+/).filter((w) => w.length > 4);
      for (const w of words) if (text.includes(w)) score += 1;
    }
    if (teamCtx && c.cat === 'equipos') score += 5;
    if (score >= 2) scored.push({ ...c, _score: score });
  }
  scored.sort((a, b) => b._score - a._score);
  return scored.slice(0, limit);
}
